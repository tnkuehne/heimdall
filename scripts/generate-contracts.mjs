import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const GENERATED_BANNER = "// Generated by `pnpm generate:contracts`. Do not edit.\n";
const CHECK = process.argv.slice(2).includes("--check");
const REPOSITORY = resolve(import.meta.dirname, "..");
const SCHEMA_PATH = resolve(REPOSITORY, "contracts/backend.schema.json");
const GENERATED_DIRECTORY = resolve(REPOSITORY, "extension/generated");

const schema = JSON.parse(await readFile(SCHEMA_PATH, "utf8"));
const contracts = contractDefinitions(schema);

const types = await compile(schema, "BackendContract", {
	additionalProperties: false,
	bannerComment: GENERATED_BANNER.trimEnd(),
	declareExternallyReferenced: true,
	style: {
		bracketSpacing: true,
		printWidth: 100,
		semi: true,
		singleQuote: false,
		tabWidth: 4,
		trailingComma: "all",
		useTabs: true,
	},
	unknownAny: true,
	unreachableDefinitions: true,
});

const ajv = new Ajv2020({
	allErrors: true,
	code: { esm: true, lines: true, source: true },
	strict: true,
	validateFormats: false,
});
ajv.addSchema(schema);

const validatorReferences = Object.fromEntries(
	contracts.map(({ name, reference }) => [`validate${name}`, `${schema.$id}${reference}`]),
);
for (const [validatorName, reference] of Object.entries(validatorReferences)) {
	if (!ajv.getSchema(reference))
		throw new Error(`Ajv could not resolve ${validatorName} from ${reference}`);
}

const validators = `${GENERATED_BANNER}${standaloneCode(ajv, validatorReferences)}`;
const declarations = validatorDeclarations(contracts);

await Promise.all([
	writeOrCheck(resolve(GENERATED_DIRECTORY, "contracts.ts"), types),
	writeOrCheck(resolve(GENERATED_DIRECTORY, "validators.js"), validators),
	writeOrCheck(resolve(GENERATED_DIRECTORY, "validators.d.ts"), declarations),
]);

function contractDefinitions(rootSchema) {
	if (!rootSchema.$id) throw new Error("contract schema is missing $id");
	if (!rootSchema.properties) throw new Error("contract schema is missing root properties");

	return Object.entries(rootSchema.properties).map(([property, propertySchema]) => {
		const reference = propertySchema.$ref;
		if (!reference?.startsWith("#/$defs/"))
			throw new Error(`contract property ${property} must reference a named $defs schema`);

		return { name: reference.slice("#/$defs/".length), reference };
	});
}

function validatorDeclarations(definitions) {
	const typeNames = definitions.map(({ name }) => name).join(", ");
	const validators = definitions
		.map(({ name }) => `export declare const validate${name}: ContractValidator<${name}>;`)
		.join("\n");

	return `${GENERATED_BANNER}import type { ${typeNames} } from "./contracts.js";

export interface ContractValidationError {
	readonly instancePath: string;
	readonly schemaPath: string;
	readonly keyword: string;
	readonly message?: string;
}

export interface ContractValidator<T> {
	(value: unknown): value is T;
	readonly errors?: readonly ContractValidationError[] | null;
}

${validators}
`;
}

async function writeOrCheck(path, expected) {
	if (CHECK) {
		let actual;
		try {
			actual = await readFile(path, "utf8");
		} catch (cause) {
			throw new Error(`generated contract is missing: ${path}`, { cause });
		}
		if (actual !== expected)
			throw new Error(`generated contract is stale: ${path}; run pnpm generate:contracts`);
		return;
	}

	await mkdir(dirname(path), { recursive: true });
	await writeFile(path, expected);
}
